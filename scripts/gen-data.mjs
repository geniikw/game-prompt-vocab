// Generates data/*.json from scripts/terms-*.mjs, skipping entries that already exist in other data files.
import fs from 'fs';
import path from 'path';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const dataDir = path.join(root, 'data');
const mine = new Set();
const sets = [];
for (const f of fs.readdirSync(path.join(root, 'scripts')).filter((f) => /^terms-.*\.mjs$/.test(f)).sort()) {
  sets.push((await import(path.join(root, 'scripts', f))).default);
}
const norm = (s) => s.toLowerCase().replace(/\(.*?\)/g, '').replace(/[^a-z0-9가-힣]/g, '');
const outName = (deck) => `${deck}-plus.json`;
// existing (not generated by us)
const existing = [];
for (const f of fs.readdirSync(dataDir)) {
  if (f.endsWith('-plus.json')) continue;
  existing.push(...JSON.parse(fs.readFileSync(path.join(dataDir, f), 'utf8')));
}
const seenId = new Set(existing.map((t) => t.id));
const seenKey = new Set(existing.flatMap((t) => [norm(t.en), norm(t.term)]));
let total = 0, skipped = [];
for (const set of sets) for (const [deck, rows] of Object.entries(set)) {
  const out = [];
  for (const [slug, term, en, definition, example, tags, aliases] of rows) {
    const id = `${deck}-${slug}`;
    if (seenId.has(id) || seenKey.has(norm(en)) || seenKey.has(norm(term))) { skipped.push(`${deck}:${term}`); continue; }
    seenId.add(id); seenKey.add(norm(en)); seenKey.add(norm(term));
    const t = { id, deck, term, en, definition, example };
    if (tags?.length) t.tags = tags;
    if (aliases?.length) t.aliases = aliases;
    out.push(t);
  }
  fs.writeFileSync(path.join(dataDir, outName(deck)), JSON.stringify(out, null, 2) + '\n');
  total += out.length;
}
console.log('generated', total, 'skipped duplicates:', skipped.join(', ') || 'none');
